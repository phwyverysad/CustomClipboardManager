    public static class I18n
    {
        private static string _currentLanguage = "en";
        private static AppStrings _current = new AppStrings();

        public static string CurrentLanguage => _currentLanguage;
        public static AppStrings Current => _current;
        public static CultureInfo Culture { get; private set; } = CultureInfo.InvariantCulture;

        public static event Action? LanguageChanged;

        static I18n()
        {
            string saved = LoadSavedLanguage();
            SetLanguage(saved);
        }

        public static void SetLanguage(string langCode)
        {
            _currentLanguage = NormalizeLanguageCode(langCode);
            _current = BuildStrings(_currentLanguage);
            try
            {
                Culture = _currentLanguage switch
                {
                    "th" => CultureInfo.GetCultureInfo("th-TH"),
                    "ja" => CultureInfo.GetCultureInfo("ja-JP"),
                    "zh-Hans" => CultureInfo.GetCultureInfo("zh-CN"),
                    "zh-Hant" => CultureInfo.GetCultureInfo("zh-TW"),
                    "de" => CultureInfo.GetCultureInfo("de-DE"),
                    "es" => CultureInfo.GetCultureInfo("es-ES"),
                    "fr" => CultureInfo.GetCultureInfo("fr-FR"),
                    "ko" => CultureInfo.GetCultureInfo("ko-KR"),
                    "ru" => CultureInfo.GetCultureInfo("ru-RU"),
                    _ => CultureInfo.GetCultureInfo("en-US")
                };
            }
            catch
            {
                Culture = CultureInfo.InvariantCulture;
            }
            LanguageChanged?.Invoke();
        }

        public static string NormalizeLanguageCode(string? code)
        {
            if (string.IsNullOrWhiteSpace(code)) return "en";
            string lower = code.Trim().ToLowerInvariant();
            if (lower.StartsWith("th")) return "th";
            if (lower.StartsWith("ja")) return "ja";
            if (lower.StartsWith("zh-hant") || lower.StartsWith("zh-tw") || lower.StartsWith("zh-hk")) return "zh-Hant";
            if (lower.StartsWith("zh")) return "zh-Hans";
            if (lower.StartsWith("de")) return "de";
            if (lower.StartsWith("es")) return "es";
            if (lower.StartsWith("fr")) return "fr";
            if (lower.StartsWith("ko")) return "ko";
            if (lower.StartsWith("ru")) return "ru";
            return "en";
        }

        public static string LoadSavedLanguage(string? targetDir = null)
        {
            // 1. App directory language.json
            try
            {
                string baseDir = targetDir ?? AppDomain.CurrentDomain.BaseDirectory;
                string langFile = Path.Combine(baseDir, "language.json");
                if (File.Exists(langFile))
                {
                    string content = File.ReadAllText(langFile);
                    var match = Regex.Match(content, @"""Language""\s*:\s*""([^""]+)""");
                    if (match.Success) return match.Groups[1].Value.Trim();
                }
            }
            catch { }

            // 2. Registry HKCU\Software\CustomClipboardManager\Language
            try
            {
                using var key = Registry.CurrentUser.OpenSubKey(@"Software\CustomClipboardManager");
                string? regLang = key?.GetValue("Language") as string;
                if (!string.IsNullOrEmpty(regLang)) return regLang.Trim();
            }
            catch { }

            // 3. Fallback to System Culture
            string sysLang = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            return NormalizeLanguageCode(sysLang);
        }

        public static void SaveLanguage(string langCode, string? targetDir = null)
        {
            string norm = NormalizeLanguageCode(langCode);
            SetLanguage(norm);

            try
            {
                string baseDir = targetDir ?? AppDomain.CurrentDomain.BaseDirectory;
                string langFile = Path.Combine(baseDir, "language.json");
                File.WriteAllText(langFile, $"{{\"Language\": \"{norm}\"}}");
            }
            catch { }

            try
            {
                using var key = Registry.CurrentUser.CreateSubKey(@"Software\CustomClipboardManager");
                key?.SetValue("Language", norm);
            }
            catch { }
        }

